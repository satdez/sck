// Regenerates the Creator Kit lockup motion block in src/app/globals.css (everything from its marker to the end of
// the file) and the matching easings in the /logo cards.
// Run: node --experimental-strip-types scripts/gen-motion-css.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { coinPose, springEasing, COIN_MS } from "../src/lib/coin-motion.ts";

const MARK = "/* ── Creator Kit lockup motion";
const BLOCK_SPRING = springEasing(0.6); // blocks sliding in: ~9% overshoot, then rest
const POP_SPRING = springEasing(0.72); // letters: a gentler settle
const SOFT = "cubic-bezier(0.5, 0, 0.15, 1.06)"; // fallback where linear() isn't supported
const OUT_QUAD = "cubic-bezier(0.25, 0.46, 0.45, 0.94)"; // rising against gravity
const IN_QUAD = "cubic-bezier(0.55, 0.085, 0.68, 0.53)"; // falling with it

// the coin, sampled from the physical model so every property follows the same toss
const N = 60;
const r = (n) => Math.round(n * 1000) / 1000;
const kf = [];
for (let i = 0; i <= N; i++) {
  const T = i / N;
  const { turn, y, sy } = coinPose(T);
  const cos = Math.cos(turn);
  const sin = Math.sin(turn);
  const s = Math.max(Math.abs(cos), 0.04);
  const o = 1.6 * sin;
  const f = (cos >= 0 ? 1 : -1) * 3.2 * sin;
  kf.push(`${Math.round(T * 1000) / 10}% { --s: ${r(s)}; --o: ${r(o)}px; --f: ${r(f)}px; translate: 0 ${r(y * 42)}%; scale: 1 ${r(sy)}; }`);
}

const css = `${MARK} (generated by scripts/gen-motion-css.mjs: edit it there) ───────────────
   The home logo (.hl) plays on load (.play) and again on hover/tap (.hov). The /logo cards play via .logo-stage.play.
   The bolt "o" is a coin that is tossed: wind-up dip, parabolic flight with a constant spin, then a squash-and-hop
   landing. Its edge is 5 slices that fan out as it turns. Everything else eases like a spring (overshoot, then rest). */
@property --s { syntax: "<number>"; inherits: true; initial-value: 1; }
@property --o { syntax: "<length>"; inherits: true; initial-value: 0px; }
@property --f { syntax: "<length>"; inherits: true; initial-value: 0px; }
.coin-rim, .coin-face { transform-box: fill-box; transform-origin: center; }
.coin { transform-box: fill-box; transform-origin: 50% 100%; }
.coin-rim { transform: translateX(calc(var(--k) * var(--o))) scaleX(var(--s)); }
.coin-face { transform: translateX(var(--f)) scaleX(var(--s)); }
.hl .solo { transform-box: fill-box; transform-origin: 50% 50%; }
.hl { --coin-delay: 950ms; }
.hl.hov { --coin-delay: 0ms; }

/* one toss (${COIN_MS}ms). Sampled, so the timing is linear: the easing is in the keyframes themselves */
:is(.hl.cg, .logo-stage.play) .coin { animation: coin ${COIN_MS}ms linear var(--coin-delay, 700ms) both; }
@keyframes coin {
${kf.map((l) => "  " + l).join("\n")}
}

/* on load: solo pops, CREATOR slides in from the lower right, KIT from the lower left, letters flash the 4 colours.
   Each rule is written twice: a cubic-bezier fallback, then a spring via linear() for browsers that support it. */
.hl.play .solo { animation: hl-solo-in 0.7s ${SOFT} both; animation: hl-solo-in 0.7s ${POP_SPRING} both; animation-delay: calc(var(--i) * 70ms); }
.hl.play .b1 { animation: hl-blk-right 1s ${SOFT} 280ms both; animation: hl-blk-right 1s ${BLOCK_SPRING} 280ms both; }
.hl.play .b2 { animation: hl-blk-left 0.9s ${SOFT} 760ms both; animation: hl-blk-left 0.9s ${BLOCK_SPRING} 760ms both; }
/* on hover / tap: a lighter replay (nothing fades out): letters hop under gravity, blocks pull back and spring home */
.hl.hov .solo { animation: hl-hop 0.6s both; animation-delay: calc(var(--i) * 45ms); }
.hl.hov .b1 { animation: hl-nudge-r 0.9s both; }
.hl.hov .b2 { animation: hl-nudge-l 0.9s 90ms both; }
@keyframes hl-solo-in { from { opacity: 0; transform: translateY(18px) scale(0.96); } to { opacity: 1; transform: none; } }
@keyframes hl-blk-right { from { opacity: 0; translate: 150px 100px; } 25% { opacity: 1; } to { opacity: 1; translate: 0 0; } }
@keyframes hl-blk-left { from { opacity: 0; translate: -130px 100px; } 25% { opacity: 1; } to { opacity: 1; translate: 0 0; } }
@keyframes hl-hop { 0% { translate: 0 0; animation-timing-function: ${OUT_QUAD}; } 42% { translate: 0 -7px; animation-timing-function: ${IN_QUAD}; } 100% { translate: 0 0; } }
@keyframes hl-nudge-r { 0% { translate: 0 0; animation-timing-function: ${OUT_QUAD}; } 28% { translate: 10px 7px; animation-timing-function: ${SOFT}; animation-timing-function: ${BLOCK_SPRING}; } 100% { translate: 0 0; } }
@keyframes hl-nudge-l { 0% { translate: 0 0; animation-timing-function: ${OUT_QUAD}; } 28% { translate: -10px 7px; animation-timing-function: ${SOFT}; animation-timing-function: ${BLOCK_SPRING}; } 100% { translate: 0 0; } }

/* the letters inside the blocks flash through four colours in a quick wave, then settle back to white */
.hl, .logo-stage { --c1: #6fd68b; --c2: #d87cf6; --c3: #f2516e; --c4: #f3c72e; }
:is(.hl.play, .logo-stage.play) .b1 .lt { animation: lt-flash 0.7s calc(950ms + var(--j) * 45ms) both; }
:is(.hl.play, .logo-stage.play) .b2 .lt { animation: lt-flash 0.7s calc(1500ms + var(--j) * 45ms) both; }
.hl.hov .b1 .lt { animation: lt-flash2 0.7s calc(var(--j) * 45ms) both; }
.hl.hov .b2 .lt { animation: lt-flash2 0.7s calc(315ms + var(--j) * 45ms) both; }
@keyframes lt-flash  { 0% { fill: #fff; animation-timing-function: step-end; } 15% { fill: var(--c1); animation-timing-function: step-end; } 30% { fill: var(--c2); animation-timing-function: step-end; } 45% { fill: var(--c3); animation-timing-function: step-end; } 60% { fill: var(--c4); animation-timing-function: step-end; } 75%, 100% { fill: #fff; } }
@keyframes lt-flash2 { 0% { fill: #fff; animation-timing-function: step-end; } 15% { fill: var(--c1); animation-timing-function: step-end; } 30% { fill: var(--c2); animation-timing-function: step-end; } 45% { fill: var(--c3); animation-timing-function: step-end; } 60% { fill: var(--c4); animation-timing-function: step-end; } 75%, 100% { fill: #fff; } }
@media (prefers-reduced-motion: reduce) { .hl *, .logo-stage .coin, .logo-stage .lt { animation: none !important; } }

/* the headline's "o": a coin the size of the letter it replaces (Gilroy's o is about 0.55em), tossed shortly after load */
.coin-o { --coin-delay: 700ms; display: inline-block; width: 0.55em; height: 0.55em; vertical-align: -0.02em; margin: 0 0.012em 0 0.016em; }
.coin-o.hov { --coin-delay: 0ms; }
`;

const gp = "src/app/globals.css";
const g = readFileSync(gp, "utf8");
writeFileSync(gp, g.slice(0, g.indexOf(MARK)) + css);

// the same springs on the /logo cards
const lp = "src/app/logo/logo-grid.tsx";
let l = readFileSync(lp, "utf8");
const both = (name, dur, spring, delay) =>
  `animation: ${name} ${dur} ${SOFT}${delay ? " " + delay : ""} both; animation: ${name} ${dur} ${spring}${delay ? " " + delay : ""} both;`;
l = l
  .replace(/\.logo-stage\.play \.solo \{[^\n]*\n/, `.logo-stage.play .solo { ${both("solo-in", "0.7s", POP_SPRING)} animation-delay: calc(var(--i) * 70ms); }\n`)
  .replace(/\.logo-stage\.play \.b1 \{[^\n]*\n/, `.logo-stage.play .b1 { ${both("blk-right", "1s", BLOCK_SPRING, "280ms")} }\n`)
  .replace(/\.logo-stage\.play \.b2 \{[^\n]*\n/, `.logo-stage.play .b2 { ${both("blk-left", "0.9s", BLOCK_SPRING, "760ms")} }\n`);
writeFileSync(lp, l);
console.log("ok", css.length, "bytes of CSS;", kf.length, "coin keyframes");
